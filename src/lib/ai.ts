const NOTES_SYSTEM = `You are an expert note-taker who turns raw source material into excellent study notes.
Write clear, well-structured Markdown:
- One "# Title", then "## Sections" in the order of the source, with nested bullets for hierarchy.
- **Bold** every key term at its definition. Use tables to compare things. Use "> 💡 Example:" blockquotes for worked examples.
- ALL math, formulas, equations and chemical reactions use LaTeX: inline $x^2$ and display $$\\int_0^1 x\\,dx$$. Keep derivations step by step, never collapse them into prose.
- Keep: definitions, theorems and proofs, worked examples, data, and anything the speaker stresses ("this will be on the exam").
- Drop: greetings, jokes, administrative announcements, off-topic tangents, filler, and repetition.
- Never invent facts that are not in the source. If the speaker flagged confusion with "[?]", list those under "## Open questions".
- Finish with "## Key takeaways" (3-6 bullets).`;

export async function genNotes(s: Settings, title: string, source: string, kind: DocKind, onPartial: (text: string) => void, o: Opt = {}): Promise<string> {
  if (hasLLM(s)) {
    const parts = segments(source, 14000);
    let acc = "";
    for (let i = 0; i < parts.length; i++) {
      const note = noisy(kind) ? "This is a noisy classroom/video transcript: remove chatter and tangents but keep what the instructor emphasises.\n" : "";
      const multi = parts.length > 1 ? `This is part ${i + 1} of ${parts.length}. ${i === 0 ? 'Start with the "# Title".' : "Continue the notes: no title, no Key takeaways yet."}\n` : "";
      const prefix = acc ? acc + "\n\n" : "";
      const text = await stream(
        s,
        "smart",
        [
          { role: "system", content: NOTES_SYSTEM },
          { role: "user", content: `${note}${multi}Title: ${title}\n\nSource:\n${parts[i]}` },
        ],
        (t) => onPartial(prefix + t),
        o,
      );
      acc = prefix + text;
    }
    if (parts.length > 1) {
      const tk = await complete(s, "fast", [{ role: "user", content: `Write a "## Key takeaways" section (3-6 bullets, Markdown) for these notes:\n\n${clip(acc, 20000)}` }], o);
      acc += "\n\n" + tk;
      onPartial(acc);
    }
    return acc;
  }

  // Offline: cluster source into sections, summarise each by its top sentences.
  const lines = [`# ${title}`, "", "> Generated by the offline engine. Add an API key in Settings for much better notes.", ""];
  const kw = topKeywords(source, 8);
  if (kw.length) lines.push(`**Key terms:** ${kw.map((k) => `\`${k}\``).join(", ")}`, "");
  chunk(source, 900).forEach((c, i) => {
    lines.push(`## ${i + 1}. ${topKeywords(c, 3).map(cap).join(" · ") || `Part ${i + 1}`}`, "");
    (topSentences(c, 3).length ? topSentences(c, 3) : [c.slice(0, 200)]).forEach((t) => lines.push(`- ${t}`));
    lines.push("");
  });
  const text = lines.join("\n");
  onPartial(text);
  return text;
}

