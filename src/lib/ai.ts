type RawSection = { title: string; lesson: string; check: CheckIn };

export async function genCourse(s: Settings, title: string, material: string, o: Opt = {}): Promise<Section[]> {
  const j = await json<{ sections: RawSection[] }>(
    s,
    "smart",
    `Design a guided course of EXACTLY 12 sections on the topic, scaffolded from "Introduction and warm-up" through foundations to advanced applications. ${material.trim() ? "Base it strictly on the provided source material and follow its arc." : "No source was provided: research the topic from your own knowledge and be accurate."} Each section: a short title; a micro-lesson in Markdown (80-160 words: explanation, one concrete example, LaTeX for math); and one multiple-choice check-in question testing that lesson with 4 options, a 0-3 answer index, and a one-sentence explanation. Schema: {"sections":[{"title":string,"lesson":string,"check":{"q":string,"options":[4 strings],"answer":number,"explain":string}}]}.`,
    `Topic: ${title}\n\n${clip(material, 16000)}`,
    o,
  );
  const ok = (j?.sections ?? []).filter((x) => x?.title && x?.lesson && x?.check?.options?.length === 4 && Number.isInteger(x.check.answer));
  if (ok.length >= 6) return ok.slice(0, 12).map((x) => ({ ...x, id: uid(), done: false }));

  const sents = sentences(material);
  const kw = topKeywords(material, 40);
  const mk = (i: number, t: string, lesson: string, probe?: string): Section => {
    const term = probe ? kw.find((k) => new RegExp(`\\b${k}\\b`, "i").test(probe)) : undefined;
    const opts = term ? shuffle([term, ...shuffle(kw.filter((k) => k !== term)).slice(0, 3)]) : ["Got it", "Not sure yet", "Tell me more", "Skip"];
    return {
      id: uid(),
      title: t,
      lesson,
      done: false,
      check: term && probe
        ? { q: mask(probe, term), options: opts, answer: opts.indexOf(term), explain: `From the lesson: "${probe}"` }
        : { q: `Ready to move on from "${t}"?`, options: opts, answer: 0, explain: "Warm-up complete." },
    };
  };
  if (!sents.length) {
    return Array.from({ length: 12 }, (_, i) =>
      mk(i, i === 0 ? "Introduction and warm-up" : `Module ${i + 1}`, `Add an API key in Settings so TurboGoo can research "${title}" and write this lesson, or create the course from a file or pasted text.`),
    );
  }
  const per = Math.max(1, Math.ceil(sents.length / 12));
  return Array.from({ length: 12 }, (_, i) => {
    const g = sents.slice(i * per, i * per + per);
    const body = g.length ? g : [sents[sents.length - 1]];
    return mk(i, i === 0 ? "Introduction and warm-up" : topKeywords(body.join(" "), 2).map(cap).join(" & ") || `Module ${i + 1}`, body.map((b) => `- ${b}`).join("\n"), body[0]);
  });
}

